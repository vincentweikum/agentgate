"""Create a local .env with random client secrets (never committed).

    python scripts/dev_setup.py

Every OAuth client in config/clients.yaml gets a fresh random secret. The API,
the agent gateway, and the approvals CLI all read .env, so they agree on
secrets without anything sensitive living in the repo.
"""

from __future__ import annotations

import secrets
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
ENV = ROOT / ".env"


def main() -> int:
    if ENV.exists():
        print(".env already exists; leaving it alone. Delete it to regenerate secrets.")
        return 0
    clients = yaml.safe_load((ROOT / "config" / "clients.yaml").read_text())["clients"]
    lines = ["# Local development secrets. Generated by scripts/dev_setup.py. Never commit this file."]
    for client_id, spec in clients.items():
        lines += [f"# {client_id}", f"{spec['secret_env']}={secrets.token_urlsafe(24)}"]
    lines += ["AGENTGATE_API_URL=http://localhost:8000", ""]
    ENV.write_text("\n".join(lines))
    ENV.chmod(0o600)
    print(f"Wrote {ENV.relative_to(ROOT)} with secrets for: {', '.join(clients)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
